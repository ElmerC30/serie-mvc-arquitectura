package modelo;

/**
 * Tesitura del saxofón. Es el dato que decide qué boquillas y qué cañas le sirven a un instrumento:
 * una boquilla de alto no entra en el tudel de un tenor, y una caña de tenor es demasiado ancha para
 * una boquilla de alto.
 */
public enum Familia {
    SOPRANO, ALTO, TENOR, BARITONO
}
